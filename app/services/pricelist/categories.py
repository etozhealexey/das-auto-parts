"""Категории каталога, выводимые из названия позиции прайс-листа.

В прайсе autoeuro нет колонки с категорией, но первое слово поля «Применение»
почти всегда называет тип детали («Фильтр масляный…», «Колодки тормозные…»).
Название сопоставляется с регулярными выражениями по шагам; на каждом шаге
первое совпавшее правило побеждает:

1. Правила категорий (``CategoryRule.patterns``) — в основном по началу
   названия, то есть по типу детали. Категории проверяются в порядке
   ``_MATCH_ORDER``: специфичные раньше общих (инструмент раньше двигателя,
   «Щётка стеклоочистителя» — раньше электрики, уплотнения узлов — раньше
   общего правила «Прокладка/Сальник/Кольцо → двигатель»), а внутри правил
   исключены пересечения («Диск сцепления» не попадает в тормоза).
2. Те же правила для названия без одного-двух ведущих прилагательных
   («Шариковый подшипник», «Электрический вентилятор отопителя»).
3. Запасные правила ``_FALLBACK`` — для общих слов в начале («Кронштейн…»,
   «Трубка…», «Втулка…»): сначала ищется упоминание узла автомобиля в любом
   месте названия («…глушителя» → выхлоп, «…отопителя» → отопление), затем
   общее слово относится к самой вероятной категории («Втулка» → подвеска).

Если ничего не подошло — категория «other». Порядок ``CATEGORIES`` — это порядок
показа в каталоге, на сопоставление он не влияет.

Перед сопоставлением название нормализуется: нижний регистр, «ё» → «е»,
латинские буквы-двойники в кириллических словах («cтупица», «ФИЛЬTP»), пробел
после точки в сокращениях («Прокл.ГБЦ» → «прокл. гбц»), запятые и лишние
пробелы. Правила проверяются также на варианте без ведущего артикула или бренда
латиницей («LA-523 Фильтр…», «LAVR Очиститель…») и без слова-обёртки
«комплект/к-кт/ремкомплект/набор», чтобы «Комплект прокладок ГБЦ» попал
в «Двигатель», а «Ремкомплект суппорта» — в «Тормозную систему».
"""

import re
from dataclasses import dataclass


@dataclass(frozen=True)
class CategoryRule:
    slug: str
    title: str
    icon: str  # имя иконки из partials/icons.html (или "box", если подходящей нет)
    patterns: tuple[str, ...]  # регулярные выражения; ищутся в названии в нижнем регистре


OTHER_SLUG = "other"

# Уплотнения относятся к узлу, который уплотняют («Прокладка глушителя» → выхлоп),
# а без указания узла — к двигателю.
_SEALS = (
    r"прокладк\w*|прокладок|прокл\.?|сальник\w*|манжет\w*|кольц\w*|колец|уплотнител\w*"
    r"|уплотнительн\w*|уплотняющ\w*|уплотнени\w*|уплотнит\.|упл\.?"
)
# До двух/трёх произвольных слов между типом детали и узлом («Трос привода открывания капота»).
_W2 = r"(?:\S+ ){0,2}"
_W3 = r"(?:\S+ ){0,3}"


def _detail(
    heads: str, places: str, *, gap: str = _W3, seals: bool = False, unless: str = ""
) -> str:
    """Правило «деталь узла»: в начале одно из heads (или уплотнение, если seals), затем
    не больше gap произвольных слов и одно из places; unless — слова, отменяющие правило."""
    if seals:
        heads = f"{heads}|{_SEALS}"
    guard = f"(?!.*(?:{unless}))" if unless else ""
    return rf"^{guard}(?:{heads}) {gap}(?:{places})"


