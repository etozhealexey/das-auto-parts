# Латинские буквы, которыми в прайсе иногда набирают часть кириллического слова.
_LOOKALIKES = str.maketrans("abcehkmoptxy", "авсенкмортху")
_CYRILLIC = re.compile(r"[а-я]")
_OTHER_LATIN = re.compile(r"[dfgijlnqrsuvwz]")
# Ведущий артикул или бренд латиницей («LA-523 Фильтр…», «bi bi care Очиститель…»).
_ARTICLE_PREFIX = re.compile(r"^(?:[a-z0-9][a-z0-9\-\./_]*\s+){1,3}(?=[а-я])")
# Слово-обёртка «комплект/к-кт/ремкомплект/набор…» перед названием детали.
_KIT_PREFIX = re.compile(
    r"^(?:ремкомплект|ремкомлект|ремонтный комплект|монтажный комплект|установочный комплект"
    r"|комплект установочный|комплект|набор|рем\. ?компл(?:ект)?\.?|рем\. ?к-кт|ремк-кт"
    r"|ремком\.|ремк\.|к-кт\.?|к/кт|к-т\.?|компл\.|комп\.|кт\.)\s+(?=[а-я])"
)
# Ведущее прилагательное («Электрический…», «Шариковый…»).
_ADJECTIVE = re.compile(r"^[а-я]+(?:-[а-я]+)?(?:ый|ий|ой|ая|яя|ое|ее|ые|ие)\s+(?=[а-я])")


def _fix_lookalikes(match: re.Match[str]) -> str:
    """Латинские двойники → кириллица в словах, где нет других латинских букв («ФИЛЬTP»)."""
    word = match.group(0)
    if _CYRILLIC.search(word) and not _OTHER_LATIN.search(word):
        return word.translate(_LOOKALIKES)
    return word


def _normalize(name: str) -> str:
    """Нижний регистр, «ё» → «е», латинские двойники, пробел после точки, запятые, пробелы."""
    text = name.strip().lower().replace("ё", "е")
    text = re.sub(r"\w+", _fix_lookalikes, text)
    text = re.sub(r"^\W+", "", text)
    text = re.sub(r"\.(?=[а-яa-z])", ". ", text)
    text = re.sub(r"[,;]+", " ", text)
    return re.sub(r"\s+", " ", text).strip()


def _variants(name: str) -> tuple[str, ...]:
    """Варианты текста: нормализованный, без ведущего артикула, без слова-обёртки."""
    full = _normalize(name)
    text = _ARTICLE_PREFIX.sub("", full)
    stripped = _KIT_PREFIX.sub("", text)
    return tuple(dict.fromkeys((full, text, stripped)))


def _without_adjectives(variants: tuple[str, ...]) -> tuple[str, ...]:
    """Варианты без одного и без двух ведущих прилагательных."""
    result: list[str] = []
    for text in variants:
        for _ in range(2):
            if not _ADJECTIVE.match(text):
                break
            text = _ADJECTIVE.sub("", text)
            result.append(text)
    return tuple(dict.fromkeys(result))


def assign_category(name: str) -> str:
    """Вернуть slug категории для названия позиции; «other», если правило не нашлось."""
    variants = _variants(name)
    adjectiveless = _without_adjectives(variants)
    for texts in (variants, adjectiveless):
        for slug, patterns in _COMPILED:
            if any(p.search(v) for p in patterns for v in texts):
                return slug
    for slug, pattern in _COMPILED_FALLBACK:
        if any(pattern.search(v) for v in variants + adjectiveless):
            return slug
    return OTHER_SLUG
